import 'dotenv/config';
import express from 'express';
import handler from '../api/intelligence.js';
import retired from '../api/gemini.js';
const app = express();
app.disable('x-powered-by');
app.use(express.json({ limit: '12kb' }));
app.all('/api/intelligence', handler);
app.all('/api/gemini', retired);
app.use('/api', (_req, res) => res.status(404).json({ error: 'Recurso não encontrado.' }));
app.listen(3001, '127.0.0.1', () => console.log('CRM API local: http://127.0.0.1:3001'));
